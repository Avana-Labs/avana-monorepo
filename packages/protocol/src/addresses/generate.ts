// Builds src/addresses/generated.ts from the verified release manifests, deployments/verified/<network>-<release>.json
// (the only manifests the services and the web app load in production; deployments/README.md). Each manifest is checked
// against the manifest schema and its file name; the output is sorted by chain ID and release, so the same manifests
// always give the same file.

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { parseManifest } from "../manifest/schema.ts";
import { addressesFromManifest, compareReleases, type AvanaAddresses } from "./fromManifest.ts";

export interface AddressBook {
  /** Chain ID → release tag → addresses. */
  readonly deployments: Readonly<Record<number, Readonly<Record<string, AvanaAddresses>>>>;
  /** Chain ID → newest release tag. */
  readonly latest: Readonly<Record<number, string>>;
}

/** Reads every manifest in `<deploymentsDir>/verified/`; an absent folder is an empty book. */
export function readAddressBook(deploymentsDir: string): AddressBook {
  const dir = join(deploymentsDir, "verified");
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".json")).sort() : [];
  const byChain = new Map<number, Map<string, AvanaAddresses>>();
  const networkChain = new Map<string, number>();
  for (const file of files) {
    const m = parseManifest(readFileSync(join(dir, file), "utf8"), `verified/${file}`);
    if (file !== `${m.network}-${m.release}.json`) throw new Error(`verified/${file} holds ${m.network} ${m.release}; its name must be ${m.network}-${m.release}.json`);
    const known = networkChain.get(m.network);
    if (known !== undefined && known !== m.chainId) throw new Error(`verified/${file}: ${m.network} is chain ${known} in another manifest, ${m.chainId} here`);
    networkChain.set(m.network, m.chainId);
    const releases = byChain.get(m.chainId) ?? new Map<string, AvanaAddresses>();
    if (releases.has(m.release)) throw new Error(`verified/${file}: chain ${m.chainId} has ${m.release} twice`);
    releases.set(m.release, addressesFromManifest(m));
    byChain.set(m.chainId, releases);
  }
  const deployments: Record<number, Record<string, AvanaAddresses>> = {};
  const latest: Record<number, string> = {};
  for (const chainId of [...byChain.keys()].sort((a, b) => a - b)) {
    const releases = [...byChain.get(chainId)!.keys()].sort(compareReleases);
    deployments[chainId] = Object.fromEntries(releases.map((r) => [r, byChain.get(chainId)!.get(r)!]));
    latest[chainId] = releases[releases.length - 1]!;
  }
  return { deployments, latest };
}

/** The text of src/addresses/generated.ts for a book. */
export function renderAddressBook(book: AddressBook): string {
  const json = (v: unknown) => JSON.stringify(v, null, 2);
  // Chain IDs as numeric keys, so `keyof typeof DEPLOYMENTS` is a union of numbers.
  const byChain = (o: Readonly<Record<number, unknown>>) => {
    const entries = Object.entries(o);
    if (entries.length === 0) return "{}";
    const lines = entries.map(([k, v]) => `  ${Number(k)}: ${json(v).replace(/\n/g, "\n  ")},\n`);
    return `{\n${lines.join("")}}`;
  };
  return (
    "// SPDX-License-Identifier: BUSL-1.1\n// Copyright (c) 2026 Avana Labs\n" +
    "// AUTOGENERATED by packages/protocol/src/addresses/cli.ts from deployments/verified/. Do not edit;\n" +
    "// run `npm run addresses -w packages/protocol` after a manifest is published.\n\n" +
    'import type { AvanaAddresses } from "./fromManifest.ts";\n\n' +
    "/** Every verified deployment: chain ID → release tag → addresses. */\n" +
    `export const DEPLOYMENTS = ${byChain(book.deployments)} as const satisfies Readonly<Record<number, Readonly<Record<string, AvanaAddresses>>>>;\n\n` +
    "/** The newest verified release of each chain. */\n" +
    `export const LATEST_RELEASE = ${byChain(book.latest)} as const satisfies Readonly<Record<number, string>>;\n`
  );
}
