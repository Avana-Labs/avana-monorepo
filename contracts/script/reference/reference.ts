// Writes one network's section of the website's three reference pages (docs/reference/{addresses,parameters,
// access-controls}.md) from that network's deployment folder: its release manifest and the files the deploy writes
// beside it (world.json, the last release's config-*.json, operation-listing-activate.json, listing-oracles.json).
// The other networks' sections are kept as they are; the text around them comes from templates/.
//
// Refuses a rehearsal's folder (unless --allow-rehearsal), a manifest of another chain, and any value that is missing
// or still a placeholder, listing each one; a row the deployment legitimately lacks (no gas vault, no sequencer feed)
// is written as such. Nothing is written when a check fails.
//
// Usage, from the repo root:
//   node contracts/script/reference/reference.ts --network <id> --deployment <folder>
//     [--out docs/reference] [--date YYYY-MM-DD] [--config <config-*.json>] [--allow-rehearsal]
// <id>: ethereum, base, ethereum-sepolia, base-sepolia, local-ethereum, local-base.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildModel, loadDeployment, NETWORKS, networkOf } from "./model.ts";
import { PAGES, type Page, renderPage } from "./render.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
export const REPO = resolve(HERE, "../../..");
export const TEMPLATES = join(HERE, "templates");

const GENERATED = "<!-- Generated by contracts/script/reference/reference.ts from each network's deployment output; see docs/reference/README.md. Do not edit by hand. -->";
const start = (id: string) => `<!-- network-section:start ${id} -->`;
const end = (id: string) => `<!-- network-section:end ${id} -->`;
const SECTION = /<!-- network-section:start (\S+) -->\n([\s\S]*?)\n<!-- network-section:end \1 -->/g;

/** The network sections of a generated page, by network id. */
export function readSections(page: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const m of page.replace(/\r\n?/g, "\n").matchAll(SECTION)) out.set(m[1], m[2].trimEnd());
  return out;
}

/** A page from its template: front matter (with `updated`), the generated mark, and the sections in network order. */
export function assemble(template: string, sections: ReadonlyMap<string, string>, updated: string): string {
  const order = [...NETWORKS.map((n) => n.id).filter((id) => sections.has(id)), ...[...sections.keys()].filter((id) => !NETWORKS.some((n) => n.id === id))];
  // A blank line before the end mark keeps the mark out of the section's last paragraph or table.
  const body = order.map((id) => `${start(id)}\n${sections.get(id)}\n\n${end(id)}`).join("\n\n");
  const t = template.replace(/\r\n?/g, "\n").replace("{{updated}}", updated);
  const fm = t.indexOf("\n---\n", 4);
  if (!t.startsWith("---\n") || fm === -1) throw new Error("a template must start with front matter");
  const withMark = `${t.slice(0, fm + 5)}\n${GENERATED}\n${t.slice(fm + 5)}`;
  if (!withMark.includes("{{networks}}")) throw new Error("a template must hold {{networks}}");
  return `${withMark.replace("{{networks}}", () => body).replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}

export interface Options {
  readonly network: string;
  readonly deployment: string;
  readonly out?: string;
  readonly date?: string;
  readonly config?: string;
  readonly allowRehearsal?: boolean;
}

/** Renders the network's three sections; throws with every problem listed. Returns the page texts, written or not. */
export function generate(o: Options): Record<Page, string> {
  const net = networkOf(o.network);
  const dep = loadDeployment(net, o.deployment, { allowRehearsal: o.allowRehearsal, config: o.config });
  const problems: string[] = [];
  const model = buildModel(dep, problems);
  const outDir = o.out ?? join(REPO, "docs/reference");
  const updated = o.date ?? new Date().toISOString().slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(updated)) throw new Error(`--date ${updated} is not YYYY-MM-DD`);
  const pages = {} as Record<Page, string>;
  for (const page of PAGES) {
    const section = renderPage(page, model, problems);
    for (const bad of ["MISSING", "NaN", "undefined", "[object Object]"]) {
      if (section.includes(bad)) problems.push(`${page}: the ${net.id} section holds "${bad}"`);
    }
    for (const v of section.match(/0x[0-9a-fA-F]{40,64}/g) ?? []) {
      if (/^0x0{30}/.test(v)) problems.push(`${page}: placeholder value ${v}`);
    }
    const file = join(outDir, `${page}.md`);
    const sections = existsSync(file) ? readSections(readFileSync(file, "utf8")) : new Map<string, string>();
    sections.set(net.id, section);
    pages[page] = assemble(readFileSync(join(TEMPLATES, `${page}.md`), "utf8"), sections, updated);
  }
  if (problems.length) {
    const unique = [...new Set(problems)];
    throw new Error(`${net.id}: ${unique.length} problem(s) in ${o.deployment}; nothing written:\n${unique.map((p) => `  - ${p}`).join("\n")}`);
  }
  mkdirSync(outDir, { recursive: true });
  for (const page of PAGES) writeFileSync(join(outDir, `${page}.md`), pages[page]);
  return pages;
}

export function parseArgs(argv: readonly string[]): Options {
  const o: Record<string, string | boolean> = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--allow-rehearsal") o.allowRehearsal = true;
    else if (["--network", "--deployment", "--out", "--date", "--config"].includes(a)) {
      const v = argv[++i];
      if (v === undefined) throw new Error(`${a} needs a value`);
      o[a.slice(2)] = v;
    } else throw new Error(`unknown argument ${a}`);
  }
  if (!o.network || !o.deployment) throw new Error("usage: reference.ts --network <id> --deployment <folder> [--out <dir>] [--date YYYY-MM-DD] [--config <file>] [--allow-rehearsal]");
  return o as unknown as Options;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const o = parseArgs(process.argv.slice(2));
    generate(o);
    console.log(`${o.network}: wrote its section of ${PAGES.map((p) => `${p}.md`).join(", ")} in ${o.out ?? "docs/reference"}`);
  } catch (e) {
    console.error((e as Error).message);
    process.exit(1);
  }
}
